import { Board, BoardCard, BoardColumnId } from '../models';

const COLUMN_TITLES: Record<BoardColumnId, string> = {
  backlog: 'Backlog',
  planned: 'Planejado',
  in_progress: 'Em execução',
  in_review: 'Em revisão',
  issues: 'Pendência',
  done: 'Concluído',
};

function buildBoard(
  id: string,
  engagementId: string,
  title: string,
  cards: Record<BoardColumnId, BoardCard[]>,
): Board {
  return {
    id,
    engagementId,
    title,
    columns: (Object.keys(COLUMN_TITLES) as BoardColumnId[]).map((columnId) => ({
      id: columnId,
      title: COLUMN_TITLES[columnId],
      cards: cards[columnId],
    })),
  };
}

